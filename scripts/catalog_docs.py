"""Render the human-readable project map from the same pinned inventory."""

from pathlib import PurePosixPath
from urllib.parse import quote


ROLES = {
    "library": "公共库", "application": "应用", "bindings": "语言绑定",
    "extension": "扩展", "shell": "Shell", "suite": "安装套件", "configuration": "配置库",
}


def cell(value):
    return str(value).replace("\n", " ").replace("|", "\\|").replace("`", "'")


def render(data):
    repositories = sorted(data["repositories"], key=lambda item: item["name"])
    owners = {package["name"]: package["repository"] for package in data["packages"]}
    lines = [
        "# 项目与依赖索引", "",
        "<!-- Generated by scripts/project_z.py sync. Edit source manifests or project-z.toml. -->", "",
        f"本快照固定 **{len(repositories)} 个仓库、{len(data['packages'])} 个 Cargo package**。",
        "仓库角色来自协调清单；包名、版本和代码依赖来自实际 Cargo 工作区。内部跨仓依赖使用最新默认分支，表中的提交用于复现本次验证；注册表发布服务于外部消费者。", "",
        "直接关联同时列出 Cargo 依赖和明确声明的运行时服务、安装组件。应用内部的多个 package 在同一行展示，非 Rust 项目保留其独立构建方式。", "",
        "| 仓库 | 角色 | Cargo package 与版本 | 直接关联 | 固定源码 |",
        "| --- | --- | --- | --- | --- |",
    ]
    for repository in repositories:
        name = repository["name"]
        packages = sorted((p for p in data["packages"] if p["repository"] == name), key=lambda p: p["name"])
        dependencies = set(repository.get("requires", []))
        for package in packages:
            dependencies.update(owners[d["name"]] for d in package["dependencies"]
                                if d["name"] in owners and owners[d["name"]] != name)
        url = repository["url"].removesuffix(".git")
        if url.startswith("git@github.com:"):
            url = "https://github.com/" + url.split(":", 1)[1]
        linked = url.startswith(("https://", "http://"))
        label = f"[{cell(name)}]({url})" if linked else cell(name)
        commit = repository["commit"]
        source = f"[{commit[:12]}]({url}/tree/{commit})" if linked else commit[:12]
        versions = []
        for package in packages:
            title = f"{cell(package['name'])} {cell(package['version'])}"
            if linked:
                manifest = PurePosixPath(package["manifest"]).relative_to(repository["path"])
                versions.append(f"[{title}]({url}/blob/{commit}/{quote(str(manifest), safe='/')})")
            else:
                versions.append(title)
        lines.append(f"| {label} | {cell(ROLES.get(repository['role'], repository['role']))} | "
                     f"{'; '.join(versions) or '—'} | {', '.join(cell(d) for d in sorted(dependencies)) or '—'} | {source} |")
    lines.extend([
        "", "## 查询影响与验证", "",
        "```sh", "python3 scripts/project_z.py impact --repositories zsys",
        "python3 scripts/project_z.py resolve --all",
        "python3 scripts/project_z.py run --affected zconv -- check", "```", "",
        "`impact` 展开传递下游，`resolve --all` 核对应用和库实际使用的源码，`run` 执行明确选择的 Cargo 检查。真实桌面、设备、服务和发行制品的验收继续按各仓库说明执行。", "",
        "更新依赖后运行 `python3 scripts/project_z.py sync`。本索引和 catalog.json 一起生成；协调检查会拒绝过期的生成文件。", "",
    ])
    return "\n".join(lines)
